"use strict";
const assert=require("node:assert/strict");
const F=require("./deal-filters.js");
const NOW=Date.parse("2026-11-01T12:00:00Z");
const deal={kind:"deals",title:"Korting",priceVerified:true,discountPercent:25,
 savingsEUR:30,verifiedAt:"2026-11-01T11:00:00Z",score:88};
const big={...deal,title:"Buitenkans",discountPercent:12,savingsEUR:90};
const claim={...deal,title:"Niet gecontroleerd",priceVerified:false,discountPercent:95,savingsEUR:300};
const old={...deal,verifiedAt:"2026-10-29T06:00:00Z",discountPercent:80};
const contest={kind:"contests",title:"Hoofdprijs",verifiedAt:"2026-10-28",prizeValueEUR:5000,endDate:"2026-11-05"};
const lowContest={...contest,prizeValueEUR:300};
const rush={kind:"contests",verifiedAt:"2026-10-28",prizeValueEUR:6000,endDate:"2026-11-03"};
const other={kind:"sales",organizerVerified:false,score:99,endDate:"2026-11-07"};
assert.equal(F.isVerifiedDeal(deal,NOW),true);
assert.equal(F.isVerifiedDeal(claim,NOW),false);
assert.equal(F.isVerifiedDeal(old,NOW),false);
assert.equal(F.discount(claim,NOW),0);
assert.equal(F.savings(claim,NOW),0);
assert.equal(F.isOpportunity(deal,NOW),true);
assert.equal(F.isOpportunity(big,NOW),true);
assert.equal(F.isOpportunity(contest,NOW),true);
assert.equal(F.isOpportunity(lowContest,NOW),false);
assert.equal(F.isOpportunity(other,NOW),false);
assert.equal(F.matchesLens(claim,"discount20",NOW),false);
assert.equal(F.matchesLens(deal,"discount20",NOW),true);
assert.equal(F.matchesLens(rush,"ending",NOW),true);
assert.equal(F.matchesLens({...rush,endDate:"2026-10-01"},"ending",NOW),false);
assert.equal(F.matchesLens({wishlistMatches:["hoka-schoenen"]},"wishlist",NOW),true);
assert.equal(F.matchesLens({wishlistMatches:[]},"wishlist",NOW),false);
assert.equal(F.compare(deal,big,"saving",NOW)>0,true);
assert.equal(F.compare(claim,deal,"discount",NOW)>0,true);
assert.equal(F.compare(rush,contest,"deadline",NOW)<0,true);
console.log("Verified evidence filters passed");
