assert.deepEqual(ids("Apple Watch Ultra 3 bandje"), []);
assert.deepEqual(ids("YSL Y eau de parfum 100ml"), ["ysl-y"]);
assert.deepEqual(ids("YSL M7 Oud Absolu 80ml"), ["ysl-m7"]);
assert.deepEqual(ids(""), []);
