"use strict";
const assert = require("node:assert/strict");
const {matches, containsPhrase} = require("../../../weekdeals/wishlist_match.js");
const {readFileSync} = require("node:fs");
const {resolve} = require("node:path");
const wishlist = JSON.parse(readFileSync(resolve(__dirname, "../../../wishlist.json"), "utf8")).items;
const ids = title => matches(title, wishlist).map(hit => hit.id);
assert.equal(containsPhrase("airpods pro 3", "airpods"), true);
assert.equal(containsPhrase("airpodspro3", "airpods"), false);
assert.deepEqual(ids("Apple AirPods 4 met ANC"), ["apple-airpods"]);
assert.deepEqual(ids("Apple AirPods Pro 3 noise cancelling"), ["apple-airpods-pro"]);
assert.deepEqual(ids("Apple AirPods Max"), []);
assert.deepEqual(ids("Apple AirPods Pro hoesje"), []);
assert.deepEqual(ids("Apple MacBook Air M5 16GB"), ["apple-macbook"]);
assert.deepEqual(ids("Apple MacBook hoes 13 inch"), []);
assert.deepEqual(ids("Apple iMac M4 24 inch"), ["apple-imac"]);
assert.deepEqual(ids("HOKA Arahi 7 EU 47 1/3"), ["hoka-schoenen"]);
assert.deepEqual(ids("HOKA Clifton 9"), []);
assert.deepEqual(ids("Arc'teryx Atom Hoody XL"), ["arcteryx-outdoor"]);
assert.deepEqual(ids("Arc'teryx Atom Hoody dames"), []);
assert.deepEqual(ids("JANZEN Earth sticks"), ["janzen-earth"]);
assert.deepEqual(ids("JANZEN Summer"), []);
assert.deepEqual(ids("Lampe Berger parfum navulling 500 ml"), ["lampe-berger-geuren"]);
assert.deepEqual(ids("Maison Berger Paris navulling 1 L"), ["lampe-berger-geuren"]);
assert.deepEqual(ids("USB4 docking station 8K"), ["usb-hubs-premium"]);
assert.deepEqual(ids("USB-C hub 4 poorten"), []);
assert.deepEqual(ids("Rituals Homme douchefoam"), ["rituals-homme"]);
assert.deepEqual(ids("Rituals Sport deo"), ["rituals-sport"]);
assert.deepEqual(ids("Giraffe Original Blend 350 gram"), ["giraffe-original"]);
