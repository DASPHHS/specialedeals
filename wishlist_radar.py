#!/usr/bin/env python3
"""Publish a compact wishlist-first view of public deals, without false price claims.

Source snapshots are generated by existing approved importers. Do not crawl sites,
infer shipping costs, bypass anti-bot protection, or promote retail old-prices to proof.
"""
from __future__ import annotations

import json
import re
import unicodedata
from collections import Counter
from datetime import datetime, timedelta
from pathlib import Path
from urllib.parse import urlparse
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent
LOCAL = ZoneInfo("Europe/Amsterdam")
MAX_PER_ITEM = 7
ACCESSORY = (
    "hoesje", "beschermhoes", "protective case", "siliconen hoes", "cover",
    "adapterkabel", "watchband", "screenprotector", "beschermfolie",
)


def read_json(path: Path, fallback: dict) -> dict:
    try:
        obj = json.loads(path.read_text(encoding="utf-8"))
        return obj if isinstance(obj, dict) else fallback
    except (OSError, ValueError):
        return fallback


def norm(value: object) -> str:
    text = unicodedata.normalize("NFKD", str(value or ""))
    text = "".join(c for c in text if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", text.lower())).strip()


def contains(text: str, phrase: object) -> bool:
    needle = norm(phrase)
    return bool(needle) and f" {needle} " in f" {norm(text)} "


def matches(title: str, wish: dict) -> bool:
    text = norm(title)
    if not text or not wish.get("id"):
        return False
    terms = wish.get("matchAny") or wish.get("keywords") or []
    if not any(contains(text, term) for term in terms):
        return False
    if any(contains(text, term) for term in wish.get("excludeTerms", [])):
        return False
    wid = wish["id"]
    if wid == "dyson-handstofzuiger" and not contains(text, "Dyson"):
        return False
    if wid == "hoka-schoenen" and not contains(text, "HOKA"):
        return False
    if wid == "apple-airpods" and (contains(text, "AirPods Pro") or contains(text, "AirPods Max")):
        return False
    if wid.startswith("apple-") and any(contains(text, t) for t in ACCESSORY):
        return False
    if wid == "arcteryx-outdoor" and any(contains(text, t) for t in ("dames", "women", "womens", "kids")):
        return False
    return True


def variation_note(title: str, wish: dict) -> str:
    """Product-name matches do not prove size, specification, stock or eligibility."""
    wid = wish["id"]
    text = norm(title)
    if wid == "hoka-schoenen":
        if not (contains(text, "47 1 3") or contains(text, "47 1/3") or contains(text, "47⅓")):
            return "Herenmaat EU 47⅓ en beschikbaarheid niet bevestigd"
    if wid == "arcteryx-outdoor":
        if not any(re.search(rf"(?<!\w){size}(?!\w)", text) for size in ("xl", "l", "w32", "w33", "w34")):
            return "Gewenste herenmaat/voorraad niet bevestigd"
    if wid == "apple-airpods" and not (contains(text, "ANC") or contains(text, "ruisonderdrukking") or contains(text, "noise cancelling")):
        return "Actieve ruisonderdrukking (ANC) niet bevestigd"
    if wid == "apple-macbook" or wid == "apple-imac":
        return "Exacte configuratie, geheugen en opslag controleren"
    if wid == "premium-padel-balls":
        return "Model en aantal ballen per verpakking controleren"
    return "Exacte variant, voorraad en NL-bezorgkosten controleren"


def valid_url(url: object) -> bool:
    try:
        p = urlparse(str(url))
        return p.scheme == "https" and bool(p.hostname) and not p.username and not p.password
    except ValueError:
        return False


def fresh_offer(offer: dict, today) -> bool:
    """Reject past offers and stale unknown-end-date observations."""
    end = str(offer.get("tot") or "")[:10]
    observed = str(offer.get("waargenomen_op") or "")[:10]
    begin = str(offer.get("van") or "")[:10]
    if begin and re.fullmatch(r"\d{4}-\d{2}-\d{2}", begin) and begin > today.isoformat():
        return False
    if end and re.fullmatch(r"\d{4}-\d{2}-\d{2}", end):
        return end >= today.isoformat()
    return observed == today.isoformat()


def price_value(value):
    if isinstance(value, bool) or not isinstance(value, (float, int)):
        return None
    return round(float(value), 2) if 0 < float(value) < 100000 else None


def candidate(offer: dict, wish: dict) -> dict:
    price = price_value(offer.get("prijs"))
    bundled = offer.get("prijstype") == "bundeltotaal" or bool(offer.get("bundelaantal"))
    return {
        "id": str(offer.get("id") or "")[:150],
        "title": str(offer.get("product") or "")[:200],
        "shop": str(offer.get("winkel") or "")[:90],
        "source": str(offer.get("bron") or "")[:100],
        "url": str(offer["url"]),
        "priceEUR": price,
        "priceType": "bundel" if bundled else "winkelprijs",
        "storeDiscountPercent": round(float(offer["korting"]) * 100, 1)
            if isinstance(offer.get("korting"), (int, float))
            and not isinstance(offer.get("korting"), bool)
            and 0 < offer["korting"] <= 1 and not bundled else None,
        "endDate": str(offer.get("tot") or "")[:10] or None,
        "observedAt": str(offer.get("waargenomen_op") or "")[:10] or None,
        "variantNote": variation_note(str(offer.get("product") or ""), wish),
        "status": "Onbevestigde winkelactie",
        "verifiedDiscount": False,
        "linkType": "bronoverzicht" if str(offer.get("bron")) == "FeedMyCart" else "winkel-of-bron",
    }


def verified_deal(deal: dict, wish: dict, now: datetime) -> dict | None:
    """Accept only fresh audited deals with a genuine delivered price and reference."""
    if not deal.get("priceVerified") is True:
        return None
    try:
        disc = float(deal.get("discountPercent") or 0)
        at = datetime.fromisoformat(str(deal.get("verifiedAt") or "").replace("Z", "+00:00"))
        if at.tzinfo is None:
            return None
        age = now - at.astimezone(now.tzinfo)
    except (TypeError, ValueError, OverflowError):
        return None
    if not (disc >= max(10, float(wish.get("minimumVerifiedDiscountPercent") or 10))
            and timedelta(0) <= age <= timedelta(hours=36)):
        return None
    title = str(deal.get("title") or deal.get("product") or "")
    if not matches(title, wish) or not valid_url(deal.get("url")):
        return None
    total = price_value(deal.get("totalPriceEUR") or deal.get("allInPriceEUR")
                        or deal.get("deliveredPriceEUR"))
    reference = price_value(deal.get("referencePriceEUR") or deal.get("referencePrice"))
    if total is None or reference is None or reference <= total:
        return None
    if (reference-total)/reference*100 + .05 < disc:
        return None
    if not (deal.get("sku") or deal.get("ean") or deal.get("variantKey")):
        return None
    return {
        "title": title[:200], "shop": str(deal.get("source") or deal.get("seller") or "")[:90],
        "url": deal["url"], "totalPriceEUR": total, "referencePriceEUR": reference,
        "discountPercent": round(disc, 1), "savingsEUR": round(reference-total, 2),
        "verifiedAt": at.isoformat(), "variant": str(deal.get("variantKey") or deal.get("sku") or deal.get("ean")),
        "status": "Geverifieerde koopdeal"
    }


def produce(wishlist: dict, sources: list, audit: dict, now: datetime) -> dict:
    today = now.date()
    items = [w for w in wishlist.get("items", []) if isinstance(w, dict) and w.get("id")]
    seen = set()
    offers = []
    source_counts = Counter()
    for src in sources:
        for entry in src.get("deals", []) if isinstance(src, dict) else []:
            if not isinstance(entry, dict) or not valid_url(entry.get("url")) or not fresh_offer(entry, today):
                continue
            title = str(entry.get("product") or "")
            if len(title) < 4:
                continue
            sig = (norm(title), norm(entry.get("winkel")), str(entry.get("tot") or ""))
            if sig in seen:
                continue
            seen.add(sig)
            offers.append(entry)
            source_counts[str(entry.get("winkel") or "Onbekend")[:90]] += 1
    output_items = []
    for wish in items:
        hits = [candidate(d, wish) for d in offers if matches(d.get("product", ""), wish)]
        hits.sort(key=lambda d: (d["priceEUR"] is None, d["priceEUR"] or 1e8, d["shop"].lower()))
        confirmed = [v for v in (
            verified_deal(d, wish, now) for d in audit.get("deals", [])
            if isinstance(d, dict)
        ) if v is not None]
        confirmed.sort(key=lambda x: (-x["discountPercent"], x["totalPriceEUR"]))
        output_items.append({
            "id": str(wish["id"]), "name": str(wish.get("name") or ""),
            "category": str(wish.get("category") or "Overig"),
            "notes": str(wish.get("notes") or "")[:500],
            "targetPriceEUR": price_value(wish.get("maxPriceEUR")),
            "candidateCount": len(hits), "candidates": hits[:MAX_PER_ITEM],
            "verifiedCount": len(confirmed), "verifiedDeals": confirmed[:MAX_PER_ITEM]
        })
    return {
        "schemaVersion": 1, "updatedAt": now.isoformat(),
        "sourceSnapshots": [str(s.get("updated_at") or s.get("updatedAt") or "") for s in sources],
        "wishCount": len(output_items), "candidateCount": sum(x["candidateCount"] for x in output_items),
        "verifiedDealCount": sum(x["verifiedCount"] for x in output_items),
        "shopsSeen": len(source_counts), "shops": dict(source_counts.most_common()),
        "items": output_items,
        "policy": "Winkelacties zijn onbevestigde zoekhits. Alleen afzonderlijk geauditeerde identieke modellen met actuele NL-totaalprijs, onafhankelijke referentie en >=10% echte korting zijn koopdeals. Geen voorraad of bezorgkosten verzonnen.",
        "coverage": "Bestaande aangesloten bronnen; niet alle Nederlandse/EU webshops.",
    }


def main():
    now = datetime.now(LOCAL)
    wish = read_json(ROOT / "wishlist.json", {"items": []})
    if not wish.get("items"):
        raise SystemExit("No wishlist items: refusing to overwrite existing radar")
    feeds = [
        read_json(ROOT / "weekdeals/deals.json", {"deals": []}),
        read_json(ROOT / "weekdeals/nonfood.json", {"deals": []}),
    ]
    if sum(len(x.get("deals", [])) for x in feeds) < 5:
        raise SystemExit("Sources missing/empty: refusing to overwrite radar")
    result = produce(wish, feeds, read_json(ROOT/"verified-deals.json", {"deals": []}), now)
    path = ROOT / "verlanglijst/signalen.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(f"Wishlist radar: {result['wishCount']} wishes, {result['candidateCount']} candidates, "
          f"{result['verifiedDealCount']} audited deals, {result['shopsSeen']} shops")


if __name__ == "__main__":
    main()
